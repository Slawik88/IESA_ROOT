// «Как играть» и «Как копить опыт» рейтинга и Пропуска: блоки вместо сплошного текста, слова игрока (docs/PLAYER_COPY.md).
// Только разметка: числа опыта приходят с сервера (me.xp_by_stars, /pass), правила уровней и звёзд — те же, что в core/league_v1.py.
// Стили блоков (.gd-steps, .gd-terms, .gd-tip, .gd-cards) лежат в league-games.css: их же берут страницы обычного Ритма и Сапёра.
(() => {
  const L = () => window.League, esc = s => L().esc(String(s));
  const base = () => document.body.dataset.appBase || '';
  const guide = topic => `<a class="gd-more" href="${esc(base())}/?startapp=guide_${topic}">Подробнее в Путеводителе ›</a>`;
  const steps = items => `<ol class="gd-steps">${items.map(([h, p]) => `<li><b>${h}</b>${p}</li>`).join('')}</ol>`;
  const terms = items => `<dl class="gd-terms">${items.map(([w, p]) => `<div><dt>${w}</dt><dd>${p}</dd></div>`).join('')}</dl>`;
  const tip = text => `<p class="gd-tip">${text}</p>`;
  const help = (title, body, open = false) => `<details class="lg-help"${open ? ' open' : ''}><summary>${title}</summary>${body}</details>`;

  // Что дают звёзды: опыт приходит один раз за уровень в сезоне, дальше — только разница
  function starsTip(stars) {
    const xp = stars ? `★ — ${stars[1]}, ★★ — ${stars[2]}, ★★★ — ${stars[3]} опыта` : 'чем больше звёзд, тем больше опыта';
    return tip(`<b>Опыт Пропуска за уровень:</b> ${xp}. Даётся один раз за уровень в сезоне. Улучшил звёзды — получишь разницу.`);
  }

  const RULES = {
    minesweeper: stars => steps([
      ['Открывай клетки по цифрам', 'Цифра — сколько мин среди соседних клеток. Каждое поле можно пройти без угадывания: игра проверила это заранее.'],
      ['Ставь флаги на минах', 'Зажми клетку или включи режим «Флаг». Флаг на клетке без мины считается неверным.'],
      ['Собери звёзды', '★ — все клетки без мин открыты. ★★ — и ни одного неверного флага. ★★★ — и ты успел за щедрое время.'],
      ['Иди дальше', 'Пройдёшь уровень — откроется следующий. Поле растёт от 3×3 до 12×16, а мин становится больше.'],
    ]) + terms([['Старт', 'Первую клетку открывает сама игра, чтобы начать без угадывания.']]) + starsTip(stars) + guide('mines'),
    rhythm: stars => steps([
      ['Дойди до конца уровня', 'Уровень — короткий забег на 30–60 нажатий. У тебя 3 сердца: неверная руна или пропуск отнимают сердце.'],
      ['Выбирай дары', 'После каждых 20 нажатий можно взять дар. Дары уровня одинаковы у всех игроков, и любой дар можно пропустить.'],
      ['Собери звёзды', '★ — дошёл до конца. ★★ — набрал не меньше 70% очков идеального забега. ★★★ — не меньше 90%.'],
      ['Иди дальше', 'Пройдёшь уровень — откроется следующий. Чем дальше, тем меньше времени на нажатие.'],
    ]) + terms([['Идеальный забег', 'Без ошибок и без даров, все нажатия быстрые. Его очки — мерка для звёзд.']]) + starsTip(stars) + guide('rating'),
  };

  const rules = (game, stars) => help('Как играть в «Рейтинге»', RULES[game](stars));

  // Питомцы: что даёт опыт и сколько (таблица сервера, core/league_pass.py PET_XP), у каждого свой дневной предел
  const PET_NAMES = [['feed', 'кормление'], ['activity_done', 'завершённое занятие'], ['trail_claim', 'забранный поход или экспедиция'],
    ['tracking', 'начатое выслеживание'], ['outing', 'вылазка'], ['trial', 'испытание недели'], ['level_up', 'улучшение питомца'],
    ['camp_upgrade', 'стройка в лагере'], ['reforge', 'перековка талисмана'], ['gear_craft', 'новое снаряжение'],
    ['gear_upgrade', 'улучшение снаряжения'], ['duplicate', 'повторная карточка из сундука']];
  function petsLine(pets) {
    if (!pets) return '';
    const rows = PET_NAMES.filter(([k]) => pets.xp[k]).map(([k, name]) => `<li><span>${esc(name)}</span><b>${pets.xp[k]}</b></li>`).join('');
    return `<p class="gd-note"><b>Что у питомцев даёт опыт</b></p><ul class="gd-rows">${rows}</ul>
      <p class="gd-note">Смена питомца, смена сборки (набора настроек питомца) и «надеть / снять» опыта не дают.</p>`;
  }
  const card = (icon, title, amount, text) => `<li class="gd-card"><span class="gd-ci" aria-hidden="true">${icon}</span><b>${title}</b><em>${amount}</em><small>${text}</small></li>`;

  // «Как копить опыт»: четыре источника от самого быстрого, потом нормы дня и ключи
  function xp(me) {
    const stars = L().state.me && L().state.me.xp_by_stars, cap = me.casual ? me.casual.cap : 300, pets = me.pets;
    const gain = stars ? `${stars[1]} · ${stars[2]} · ${stars[3]}` : 'по звёздам';
    const body = `<p class="lg-rules">Опыт открывает уровни Пропуска: каждые 300 опыта — новый уровень. Откуда он берётся — от самого быстрого способа к самому медленному.</p>
      <ol class="gd-cards">
        ${card('🏅', 'Рейтинг', gain, 'за уровень: ★, ★★ и ★★★. Один раз за уровень в сезоне, ограничения по дням нет. Самый быстрый путь.')}
        ${card('🎵', 'Ритм · обычный', '1 за 300 очков', 'не больше 60 за один забег. Забег на 3000 очков даст 10 опыта.')}
        ${card('💣', 'Сапёр · обычный', '12 · 20 · 40', 'за победу на лёгком, среднем и сложном поле.')}
        ${card('🐾', 'Питомцы', pets ? `до ${pets.cap} в день` : 'каждый день', 'опыт за заботу и занятия питомцев. Своя норма на день, она не мешает играм.')}
        ${me.quests ? card('📋', 'Задания', `${me.quests.daily} · ${me.quests.weekly} · ${me.quests.vip}`, 'за весь набор дня, весь набор недели и VIP-поручение дня. За набор нажми «Забрать» в «Заданиях»; VIP-поручение засчитывается после игры.') : ''}
      </ol>
      ${tip(`<b>Норма дня.</b> Обычные Ритм и Сапёр вместе дают не больше ${cap} опыта в день${me.casual ? ` (сегодня ${me.casual.today})` : ''}. Новый день начинается в 00:00 по UTC — в Москве это 03:00.`)}
      ${petsLine(pets)}
      <p class="gd-note">🗝 <b>Ключ</b> открывает сундук. «3★+» значит: у сундука будет не меньше трёх звёзд. Бывают обычные, бронзовые, серебряные и платиновые ключи.</p>
      <p class="gd-note">В сундуках лежат еда, карточки питомцев, джокеры, Мора и Алмазы. Образов в Пропуске нет.</p>
      <p class="gd-note">После 40 уровней открывается повторяемый 41-й: 300 опыта за обычный ключ, не чаще раза в 12 часов. Опыт в ожидании сохраняется.</p>
      ${guide('xp')}`;
    const fresh = me.seasons && me.seasons.some(x => x.current && x.level < 3);   // новичку объяснение раскрыто сразу
    return help('Как копить опыт', body, !!fresh);
  }

  window.LeagueHelp = {rules, xp};
})();
