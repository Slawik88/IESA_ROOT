#!/usr/bin/env python3
"""Билды питомцев v2: находки делятся по таблице весов (нулевая сумма).
Каждый бонус поднимает вес одной категории, значит остальные категории реже.
Запуск: python3 tools/pets_v2_build_sim.py"""
BASE = {"Корм": 40, "Материал": 30, "Печать/карта": 12, "Талисман": 8, "Осколок эха": 2, "Бонус Следов": 8}
CAP = 2.5          # ни один множитель категории не выше ×2.5
ROLLS = {3: 1, 6: 2, 9: 3}   # бросков находки за поход
BUILDS = {
    "без сборки (кот, лес)":              {"Корм": 1.4},
    "Кормилец (кот + Кормилец + Запасливый)": {"Корм": 2.0, "Материал": 0.8, "Печать/карта": 0.7},
    "Мастер (жук + Хранитель + Старатель)": {"Материал": 2.0, "Талисман": 1.6, "Корм": 0.7},
    "Архивариус (сова + Искатель + Скрупулёзный)": {"Печать/карта": 2.5, "Осколок эха": 2.0, "Корм": 0.6, "Материал": 0.7},
    "Охотник за эхом (рысь + Искатель + Азартный)": {"Осколок эха": 2.5, "Печать/карта": 1.5, "Бонус Следов": 0.6, "Корм": 0.7},
    "Универсал (дракон, без черт)":        {k: 1.15 for k in BASE},
}


def shares(mods: dict) -> dict:
    w = {k: BASE[k] * min(CAP, mods.get(k, 1.0)) for k in BASE}
    total = sum(w.values())
    return {k: v / total for k, v in w.items()}


if __name__ == "__main__":
    rolls_per_month = 30 * 5   # 1 девятичасовой + 1 шестичасовой поход в день = 5 бросков
    print(f"{'сборка':<48}" + "".join(f"{k:>14}" for k in BASE))
    for name, mods in BUILDS.items():
        s = shares(mods)
        print(f"{name:<48}" + "".join(f"{s[k] * rolls_per_month:>14.1f}" for k in BASE))
