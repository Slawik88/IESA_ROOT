"""Обращения игрока к администрации из лички с ботом: чистые правила (без базы и Telegram).

Игрок пишет боту «бот обращение …». Обращение получает персонал (та же роль, что открывает «Жалобы» в админке), отвечает
кнопкой «Ответить», и ответ приходит игроку в личку. Это ответ на его собственное обращение, а не рассылка, поэтому
согласие на уведомления здесь не нужно.
"""
from __future__ import annotations

MIN_TEXT = 8              # короче — это не обращение
MAX_TEXT = 600
MAX_ANSWER = 1000
DAILY_LIMIT = 3           # новых обращений от одного игрока за скользящие сутки
OPEN_LIMIT = 2            # столько обращений игрока может одновременно ждать ответа
MAX_RECIPIENTS = 20       # сколько сотрудников получают карточку нового обращения
STAFF_SECTION = "section:reports"   # право открывать обращения = право открывать «Жалобы» в админке
STAFF_DEFAULT_RANK = 2
LIST_LIMIT = 10           # «бот обращения» показывает не больше стольких открытых

STATUS_TITLES = {"new": "Ждёт ответа", "answered": "Отвечено", "closed": "Закрыто без ответа"}
ANSWER_MARK = "✍️ Ответ на обращение №"   # по этой строке бот узнаёт ответ сотрудника на подсказку «Ответить»


def clean_text(value: str, limit: int) -> str:
    """Обращение без лишних пробелов и пустых строк; управляющие символы не пропускаем."""
    text = "".join(ch for ch in str(value or "") if ch >= " " or ch in "\n\t")
    return "\n".join(line.rstrip() for line in text.strip().splitlines() if line.strip())[:limit].strip()
