def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def doc_to_html(md: str) -> str:
    """Минимальный рендер текста документа в безопасный HTML (без внешних либ).
    Правила: ЗАГЛАВНАЯ строка-заголовок → <h2>; '1. ...' → <h3>;
    '1.1. ...' и прочее → <p>; пустая строка — разделитель абзацев."""
    out: list[str] = []
    for raw in md.strip().split("\n"):
        line = raw.strip()
        if not line:
            continue
        esc = _esc(line)
        # Заголовок документа (ALL CAPS, длинная строка)
        if len(line) > 12 and line == line.upper() and any(c.isalpha() for c in line):
            out.append(f"<h2>{esc}</h2>")
        # Раздел вида "1. Заголовок" (один номер с точкой, без под-нумерации)
        elif _is_section(line):
            out.append(f"<h3>{esc}</h3>")
        else:
            out.append(f"<p>{esc}</p>")
    return "\n".join(out)


def _is_section(line: str) -> bool:
    head = line.split(".", 1)[0]
    return head.isdigit() and ". " in line[:6] and not _has_subnumber(line)


def _has_subnumber(line: str) -> bool:
    # "1.1." / "2.4." — под-пункт (не раздел)
    parts = line.split(" ", 1)[0].split(".")
    return len([p for p in parts if p.isdigit()]) >= 2
